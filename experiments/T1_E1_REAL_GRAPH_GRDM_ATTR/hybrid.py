def attribute_statistics(real, hybrid, meta, domains, dimension_tables, target):
    """Per generated column: marginals real vs hybrid, and same-node agreement.

    Same-node agreement says how much of a specific row's real value the generated value at
    that node still carries. GRDM samples each node from noise given only the graph, so this
    is the node-specific information the graph conditioning transmits.
    """
    stats = {}
    for t in meta["tables"]:
        tstats = {"rows": len(real[t]), "columns": {}}
        for c in nonkey_columns(real[t]):
            role = (
                "dimension (real)" if t in dimension_tables
                else "target (real)" if target is not None and (t, c) == tuple(target)
                else "generated"
            )
            r = pd.to_numeric(real[t][c], errors="coerce").to_numpy(dtype=float)
            h = pd.to_numeric(hybrid[t][c], errors="coerce").to_numpy(dtype=float)
            kind = domains[t].get(c, {}).get("type", "?")
            e = {"role": role, "type": kind}
            if kind == "discrete":
                rc = pd.Series(r).value_counts(normalize=True)
                hc = pd.Series(h).value_counts(normalize=True)
                idx = rc.index.union(hc.index)
                rc, hc = rc.reindex(idx, fill_value=0), hc.reindex(idx, fill_value=0)
                e["n_levels_real_hybrid"] = [int((rc > 0).sum()), int((hc > 0).sum())]
                e["marginal_tv_distance"] = round(float(0.5 * np.abs(rc - hc).sum()), 4)
                e["same_node_match_rate"] = round(float(np.mean(r == h)), 4)
                e["same_node_match_rate_if_independent"] = round(float((rc * hc).sum()), 4)
            else:
                e["mean_real_hybrid"] = [round(float(np.nanmean(r)), 4), round(float(np.nanmean(h)), 4)]
                e["sd_real_hybrid"] = [round(float(np.nanstd(r)), 4), round(float(np.nanstd(h)), 4)]
                ok = ~(np.isnan(r) | np.isnan(h))
                if ok.sum() > 2 and np.nanstd(r) > 0 and np.nanstd(h) > 0:
                    e["same_node_pearson"] = round(float(np.corrcoef(r[ok], h[ok])[0, 1]), 4)
                    e["same_node_spearman"] = round(float(
                        pd.Series(r[ok]).rank().corr(pd.Series(h[ok]).rank())
                    ), 4)
            tstats["columns"][c] = e
        stats[t] = tstats
    return stats
