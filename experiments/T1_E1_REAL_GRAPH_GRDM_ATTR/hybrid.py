"""Build the T1_E1 hybrid database (REAL graph + GRDM attributes + REAL target) and check it.

How GRDM's output maps onto the real rows
-----------------------------------------
GRDM never sees the CSV key values. `RDBDiffDataset.get_db()` calls relbench's
`Database.reindex_pkeys_and_fkeys()`, which (with `time_col=None`, as here) replaces every
primary key by its row position in the CSV and pushes every foreign key through the parent's
pk -> position map. `make_pkey_fkey_graph` then asserts pk == arange(n), so graph node i of
table t *is* CSV row i of table t. In `main.py --fixed_structure` the sampled attribute matrix
of node type t is written back row-for-row into a copy of that reindexed database, so

    GRDM output row i of table t  <->  real CSV row i of table t.

`build_hybrid` relies on that identity and proves it per table instead of assuming it: the
GRDM output's pk column must equal arange(n), and each of its fk columns must equal the real
fk column mapped through the parent's pk -> position map. Any permutation of rows would break
the second equality. No row is ever matched by attribute value, and nothing is shuffled.

The hybrid keeps the real CSV's key values, row order and column order. Only non-key columns
of generated tables are replaced; dimension tables (Berka `district`) are conditioned on and
never generated by GRDM, so they stay real (GRDM's own copy of them differs from the real one
only by a quantile-transform round trip, e.g. A15 -1 -> -0.9986, which is not attribute
generation). Finally the task's target column, if it is an attribute, is restored to its real
values.
"""

import hashlib
import os

import numpy as np
import pandas as pd

# Where each downstream task's label lives. None = the label is a function of the graph alone
# (Berka card ownership: does the disposition have a child row in `card`), so it is real as
# soon as the graph is.
TASK_TARGETS = {
    "berka_loan_default": ("loan", "status"),
    "berka_card_ownership": None,
    "california_inctot": ("individual", "INCTOT"),
    "california_empstat": ("individual", "EMPSTAT"),
}


def is_key(col):
    return col.endswith("_id")


def key_columns(df):
    return [c for c in df.columns if is_key(c)]


def nonkey_columns(df):
    return [c for c in df.columns if not is_key(c)]


def load_grdm_output(syn_db_dir, table_names):
    return {t: pd.read_csv(os.path.join(syn_db_dir, f"{t}_synthetic.csv")) for t in table_names}


def position_maps(real, meta):
    """{table: Series pk value -> row position}, i.e. relbench's reindexing."""
    return {
        t: pd.Series(np.arange(len(real[t])), index=real[t][f"{t}_id"].to_numpy())
        for t in meta["tables"]
    }


def verify_row_mapping(real, grdm, meta):
    """Prove GRDM row i == real row i for every table. Returns a per-table report."""
    pos = position_maps(real, meta)
    report = {}
    for t, spec in meta["tables"].items():
        r, s = real[t], grdm[t]
        entry = {"rows_real": len(r), "rows_grdm": len(s)}
        entry["same_row_count"] = len(r) == len(s)
        entry["grdm_pk_is_row_position"] = bool(
            entry["same_row_count"] and (s[f"{t}_id"].to_numpy() == np.arange(len(s))).all()
        )
        fk_ok = {}
        for parent in spec["parents"]:
            key = f"{parent}_id"
            expected = r[key].map(pos[parent]).to_numpy()
            fk_ok[key] = bool(
                entry["same_row_count"]
                and not np.isnan(expected.astype(float)).any()
                and (s[key].to_numpy() == expected).all()
            )
        entry["grdm_fk_equals_real_fk_reindexed"] = fk_ok
        entry["same_nonkey_columns"] = sorted(nonkey_columns(r)) == sorted(nonkey_columns(s))
        entry["ok"] = (
            entry["same_row_count"]
            and entry["grdm_pk_is_row_position"]
            and all(fk_ok.values())
            and entry["same_nonkey_columns"]
        )
        report[t] = entry
    return report


def build_hybrid(real, grdm, meta, dimension_tables=(), target=None):
    """REAL keys + GRDM non-key attributes (row i <- GRDM row i) + REAL target column."""
    mapping = verify_row_mapping(real, grdm, meta)
    bad = [t for t, e in mapping.items() if not e["ok"]]
    if bad:
        raise AssertionError(f"GRDM output does not map row-for-row onto the real graph: {bad}")

    hybrid = {}
    for t in meta["tables"]:
        h = real[t].copy()
        if t not in dimension_tables:
            for c in nonkey_columns(h):
                h[c] = grdm[t][c].to_numpy()
        hybrid[t] = h
    if target is not None:
        t, c = target
        hybrid[t][c] = real[t][c].to_numpy()
    return hybrid, mapping


def build_row_permuted(real, meta, dimension_tables=(), target=None, seed=0):
    """Supplementary reference: REAL keys + real attribute rows shuffled between nodes of the
    same table + REAL target. Keeps each table's joint attribute distribution exactly but cuts
    every link between a node's attributes and its place in the graph."""
    rng = np.random.default_rng(seed)
    out = {}
    for t in meta["tables"]:
        h = real[t].copy()
        if t not in dimension_tables:
            perm = rng.permutation(len(h))
            cols = nonkey_columns(h)
            h[cols] = h[cols].to_numpy()[perm]
        out[t] = h
    if target is not None:
        t, c = target
        out[t][c] = real[t][c].to_numpy()
    return out


