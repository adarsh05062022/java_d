def _edge_arrays(tables, meta):
    """{(parent, child): int64 array of (child_pk, parent_pk) edges, sorted}."""
    edges = {}
    for parent, child in meta["relation_order"]:
        if parent is None:
            continue
        e = tables[child][[f"{child}_id", f"{parent}_id"]].to_numpy(dtype=np.int64)
        e = e[np.lexsort((e[:, 1], e[:, 0]))]
        edges[f"{parent}->{child}"] = e
    return edges


def graph_fingerprint(tables, meta):
    h = hashlib.sha256()
    for name, e in sorted(_edge_arrays(tables, meta).items()):
        h.update(name.encode())
        h.update(np.ascontiguousarray(e).tobytes())
    for t in sorted(meta["tables"]):
        h.update(t.encode())
        h.update(tables[t][f"{t}_id"].to_numpy(dtype=np.int64).tobytes())
    return h.hexdigest()


def _differ(a, b):
    a = pd.to_numeric(pd.Series(a), errors="coerce").to_numpy(dtype=float)
    b = pd.to_numeric(pd.Series(b), errors="coerce").to_numpy(dtype=float)
    both_nan = np.isnan(a) & np.isnan(b)
    return ~(np.isclose(a, b, rtol=0, atol=1e-9) | both_nan)


def sanity_checks(real, hybrid, meta, task, domains, test_tables, dimension_tables, target,
                  build_features, cat_spec_real=None, expect_attributes_differ=True):
    """The nine checks of the experiment spec. Returns (all_passed, report)."""
    rep = {}

    # 1. number of tables
    rep["1_same_tables"] = {
        "real": sorted(real), "hybrid": sorted(hybrid), "pass": sorted(real) == sorted(hybrid)
    }

    # 2. rows per table
    rows = {t: [len(real[t]), len(hybrid[t])] for t in meta["tables"]}
    rep["2_same_row_counts"] = {
        "rows_real_hybrid": rows, "pass": all(a == b for a, b in rows.values())
    }

    # 3. primary keys, value for value in the same row order
    pk = {t: bool((real[t][f"{t}_id"].to_numpy() == hybrid[t][f"{t}_id"].to_numpy()).all())
          for t in meta["tables"]}
    rep["3_pk_unchanged"] = {"per_table": pk, "pass": all(pk.values())}

    # 4. foreign keys
    fk = {}
    for t, spec in meta["tables"].items():
        for parent in spec["parents"]:
            key = f"{parent}_id"
            fk[f"{t}.{key}"] = bool((real[t][key].to_numpy() == hybrid[t][key].to_numpy()).all())
    rep["4_fk_unchanged"] = {"per_fk": fk, "pass": all(fk.values())}

    # 5. graph topology: identical edge sets per relation, identical degree sequences, same hash
    er, eh = _edge_arrays(real, meta), _edge_arrays(hybrid, meta)
    same_edges = {k: bool(np.array_equal(er[k], eh[k])) for k in er}
    deg = {}
    for parent, child in meta["relation_order"]:
        if parent is None:
            continue
        key = f"{parent}_id"
        dr = real[parent][key].map(real[child][key].value_counts()).fillna(0).to_numpy()
        dh = hybrid[parent][key].map(hybrid[child][key].value_counts()).fillna(0).to_numpy()
        deg[f"{parent}->{child}"] = bool(np.array_equal(dr, dh))
    fr, fh = graph_fingerprint(real, meta), graph_fingerprint(hybrid, meta)
    rep["5_graph_topology_unchanged"] = {
        "edges_equal_per_relation": same_edges,
        "degree_sequences_equal": deg,
        "fingerprint_real": fr,
        "fingerprint_hybrid": fh,
        "REAL_GRAPH == HYBRID_GRAPH": fr == fh,
        "pass": fr == fh and all(same_edges.values()) and all(deg.values()),
    }

    # 6. only non-key attributes differ
    cols = {}
    keys_identical = True
    for t in meta["tables"]:
        for c in real[t].columns:
            d = _differ(real[t][c], hybrid[t][c])
            entry = {"frac_rows_differing": round(float(d.mean()), 6) if len(d) else 0.0}
            if is_key(c):
                entry["role"] = "key"
                keys_identical &= not d.any()
            elif t in dimension_tables:
                entry["role"] = "dimension-table attribute (held real by GRDM)"
            elif target is not None and (t, c) == tuple(target):
                entry["role"] = "target (restored to real)"
            else:
                entry["role"] = "generated attribute"
            cols[f"{t}.{c}"] = entry
    generated = {k: v for k, v in cols.items() if v["role"] == "generated attribute"}
    must_match = {k: v for k, v in cols.items() if v["role"] != "generated attribute"}
    attrs_differ = all(v["frac_rows_differing"] > 0 for v in generated.values())
    rep["6_only_nonkey_attributes_differ"] = {
        "columns": cols,
        "all_keys_identical": keys_identical,
        "all_non_generated_columns_identical": all(
            v["frac_rows_differing"] == 0 for v in must_match.values()
        ),
        "every_generated_column_differs_somewhere": attrs_differ,
        "pass": keys_identical
        and all(v["frac_rows_differing"] == 0 for v in must_match.values())
        and (attrs_differ or not expect_attributes_differ),
    }

    # 7. target labels: the column itself, and the task's y vector row for row
    X_r, y_r, cat_r = build_features(real, domains)
    X_h, y_h, cat_h = build_features(hybrid, domains)
    y_equal = len(y_r) == len(y_h) and bool(
        np.array_equal(np.asarray(y_r, dtype=float), np.asarray(y_h, dtype=float))
    )
    tgt = {"task_label_vector_equal": y_equal, "n_labels": int(len(y_r))}
    if target is not None:
        t, c = target
        tgt["target_column"] = f"{t}.{c}"
        tgt["target_column_equal"] = bool(
            (real[t][c].to_numpy() == hybrid[t][c].to_numpy()).all()
        )
    else:
        tgt["target_column"] = "derived from graph structure (no attribute)"
        tgt["target_column_equal"] = True
    if task.kind == "binclass":
        tgt["positives_real_hybrid"] = [int(np.sum(y_r)), int(np.sum(y_h))]
    tgt["REAL_TARGET == HYBRID_TARGET"] = y_equal and tgt["target_column_equal"]
    tgt["pass"] = tgt["REAL_TARGET == HYBRID_TARGET"]
    rep["7_target_unchanged"] = tgt

    # 8. leakage: hybrid rows are exactly the training rows, disjoint from the test rows
    # (except dimension tables, which downstream.run deliberately shares), and the target
    # column never reaches X.
    leak = {}
    for t in meta["tables"]:
        ids_h = set(hybrid[t][f"{t}_id"])
        ids_r = set(real[t][f"{t}_id"])
        ids_test = set(test_tables[t][f"{t}_id"])
        leak[t] = {
            "hybrid_ids_equal_train_ids": ids_h == ids_r,
            "overlap_with_test_ids": len(ids_h & ids_test),
            "shared_dimension_table": t in dimension_tables,
        }
    target_in_X = bool(task.target_col) and task.target_col in X_h.columns
    rep["8_no_train_test_leakage"] = {
        "per_table": leak,
        "target_col_in_features": target_in_X,
        "pass": all(
            v["hybrid_ids_equal_train_ids"]
            and (v["overlap_with_test_ids"] == 0 or v["shared_dimension_table"])
            for v in leak.values()
        )
        and not target_in_X,
    }

    # 9. feature matrix compatible with the downstream model
    from downstream.data import align_feature_dtypes

    (Xr_al,), _ = align_feature_dtypes([X_r], cat_r)
    (Xh_al,), ood = align_feature_dtypes([X_h], cat_r)
    same_cols = list(X_r.columns) == list(X_h.columns)
    same_dtypes = same_cols and all(str(Xr_al[c].dtype) == str(Xh_al[c].dtype) for c in X_r.columns)
    rep["9_features_compatible"] = {
        "n_features_real_hybrid": [X_r.shape[1], X_h.shape[1]],
        "n_rows_real_hybrid": [X_r.shape[0], X_h.shape[0]],
        "same_columns_same_order": same_cols,
        "same_dtypes_after_alignment": same_dtypes,
        "same_categorical_spec": cat_r == cat_h,
        "out_of_domain_categorical_cells_hybrid": int(sum(ood.values())),
        "all_nan_feature_columns_hybrid": [c for c in X_h.columns if X_h[c].isna().all()],
        "pass": same_cols and same_dtypes and cat_r == cat_h and X_r.shape == X_h.shape,
    }

    passed = all(v["pass"] for v in rep.values())
    return passed, rep


